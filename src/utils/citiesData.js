/**
 * Searches the city database matching either city name or province/region name
 */
export function searchCities(query = '', limit = 50) {
  if (!query || typeof query !== 'string') {
    return ALL_CITIES.slice(0, limit);
  }

  const q = query.toLowerCase().trim();
  if (!q) return ALL_CITIES.slice(0, limit);

  const matched = [];
  for (const city of ALL_CITIES) {
    const nameMatch = city.name.toLowerCase().includes(q);
    const regionMatch = city.region && city.region.toLowerCase().includes(q);

    if (nameMatch || regionMatch) {
      matched.push(city);
      if (matched.length >= limit) break;
    }
  }

  return matched;
}
